// A 46-word sentence: the long-sentence fixture every length case derives from.
const longSentence = "The pipeline reads the source file from disk and then hands the bytes " +
	"to the analyzer, which masks every span that is not prose, and after that the detectors " +
	"run in order over the masked copy and each one emits its own violations for the report."

func TestDetectLongSentence(t *testing.T) {
	runHits(t, "long-sentence", DetectLongSentence, []hitCase{
		{"over budget", longSentence, true},
		{"under budget", "The pipeline reads the source file from disk and hands the bytes to the analyzer.", false},
		{
			"parenthetical collapses under budget",
			"The pipeline reads the source file from disk and then hands the bytes " +
				"to the analyzer (which masks every span that is not prose before anything else runs), " +
				"and then each detector emits its own violations for the report.", false,
		},
		{
			"quoted span collapses under budget",
			"The parser rejects the header when the value reads \"one two three four five six seven " +
				"eight nine ten eleven twelve thirteen fourteen fifteen sixteen\" and it stops there " +
				"before the body is read at all by anyone.", false,
		},
		{
			"pipe table row skipped",
			"| " + strings.ReplaceAll(longSentence, " ", " | ") + " |", false,
		},
		{"ATX heading line skipped", "# " + longSentence, false},
		{
			"list shape skipped",
			"- The pipeline reads the source file from disk and then hands the bytes to the analyzer\n" +
				"- which masks every span that is not prose, and after that the detectors run in order\n" +
				"- over the masked copy and each one emits its own violations for the report", false,
		},
	})
}

func TestDetectLongSentenceSpanExcludesTrailingSpace(t *testing.T) {
	v := DetectLongSentence(longSentence + "\n\nShort tail.\n")
	if len(v) != 1 {
		t.Fatalf("got %d violations, want 1", len(v))
	}
	if got := v[0].MatchedText; got != longSentence {
		t.Fatalf("span = %q, want the sentence with no trailing whitespace", got)
	}
	if v[0].Explanation != "46 words" {
		t.Fatalf("explanation = %q, want %q", v[0].Explanation, "46 words")
	}
}

