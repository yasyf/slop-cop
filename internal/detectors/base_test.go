func TestProseWordCount(t *testing.T) {
	cases := []struct {
		name string
		text string
		want int
	}{
		{"plain", "one two three", 3},
		{"parenthetical is one token", "one (two three four five) six", 3},
		{"quoted is one token", `one "two three four five" six`, 3},
		{"curly quoted is one token", "one “two three four” six", 3},
		{"attached parenthetical does not split", "call(a b c) again", 2},
		{"unbalanced paren left alone", "one (two three", 3},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := proseWordCount(c.text); got != c.want {
				t.Fatalf("proseWordCount(%q) = %d, want %d", c.text, got, c.want)
			}
		})
	}
}

func TestProseWordCountNeverExceedsFields(t *testing.T) {
	corpus := []string{
		longSentence,
		`one "two three" (four five) six`,
		"call(a b c) again \"x y\"(z)",
		"(leading) trailing (a)(b)(c)",
		`"" () a`,
		"no punctuation at all here",
		"“smart quotes” and (parens) mixed",
	}
	for _, s := range corpus {
		if got, upper := proseWordCount(s), len(strings.Fields(s)); got > upper {
			t.Fatalf("proseWordCount(%q) = %d > len(Fields) = %d", s, got, upper)
		}
	}
}

func TestMergeAbbrev(t *testing.T) {
	cases := []struct {
		name string
		text string
		want int
	}{
		{"e.g.", "Run it on a file, e.g. README.md, and stop. Then check.", 2},
		{"i.e.", "Use the base layer, i.e. the clarity rules, first. Then the slop layer.", 2},
		{"Fig.", "See Fig. 3 for the pipeline. The rest follows.", 2},
		{"initials", "The author is J. R. R. Tolkien. The book is long.", 2},
		{"no abbreviation", "One runs. Two runs.", 2},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := mergeAbbrev(splitSentences(c.text))
			if len(got) != c.want {
				t.Fatalf("mergeAbbrev(%q) = %d sentences %q, want %d", c.text, len(got), got, c.want)
			}
			if strings.Join(got, "") != c.text {
				t.Fatalf("merge lost bytes: %q != %q", strings.Join(got, ""), c.text)
			}
		})
	}
}

func TestRunBaseWiresEveryRule(t *testing.T) {
	doc := strings.Join([]string{
		longSentence,
		"One runs. Two runs. Three runs. Four runs. Five runs. Six runs. Seven runs.",
		"The report is generated by the analyzer.",
		"The flag allows you to skip the check.",
		"The command line tool prints JSON.",
		"There is a flag that controls the layer.",
		"The script makes use of the cache.",
		"The change is not uncommon.",
	}, "\n\n")
	want := []string{
		"long-sentence", "long-paragraph", "passive-voice", "padded-verb",
		"missing-hyphen", "expletive-opener", "nominalization", "elevated-register",
	}
	got := RunBase(doc)
	for _, id := range want {
		if !hasRule(got, id) {
			t.Fatalf("RunBase did not emit %s\ngot: %+v", id, got)
		}
	}
}

// RunBase is a sibling of RunClient, never a superset: the slop layer must not
// leak base-layer rule IDs, which is what makes --standard=slop reproducible.
func TestRunClientEmitsNoBaseRules(t *testing.T) {
	doc := longSentence + "\n\nThe report is generated by the analyzer. " +
		"The flag allows you to skip the check. The command line tool prints JSON. " +
		"There is a flag that controls the layer."
	for _, id := range []string{
		"long-sentence", "long-paragraph", "passive-voice", "padded-verb",
		"missing-hyphen", "expletive-opener", "nominalization",
	} {
		if hasRule(RunClient(doc), id) {
			t.Fatalf("RunClient emitted base-layer rule %s", id)
		}
	}
}

func TestBaseSpansIndexTheSource(t *testing.T) {
	doc := "Intro line.\n\n" + longSentence + "\n\nThe report is generated by the analyzer.\n\n" +
		"The command line tool prints JSON. There is a flag that controls the layer.\n\n" +
		"The script makes use of the cache and the flag allows you to skip the check.\n"
	for _, v := range RunBase(doc) {
		if v.StartIndex < 0 || v.EndIndex > len(doc) || v.StartIndex >= v.EndIndex {
			t.Fatalf("%s: span [%d,%d) out of range for %d bytes", v.RuleID, v.StartIndex, v.EndIndex, len(doc))
		}
		if got := doc[v.StartIndex:v.EndIndex]; got != v.MatchedText {
			t.Fatalf("%s: MatchedText %q does not match source slice %q", v.RuleID, v.MatchedText, got)
		}
	}
}

func TestBaseDetectorsOnEmptyInput(t *testing.T) {
	for _, d := range []func(string) []types.Violation{
		DetectLongSentence, DetectLongParagraph, DetectPassiveVoice, DetectPaddedVerb,
		DetectMissingHyphen, DetectExpletiveOpener, DetectNominalization, DetectPlainWord,
	} {
		if got := d(""); len(got) != 0 {
			t.Fatalf("empty input produced %+v", got)
		}
	}
}

// abbrevDoc is the shape that made mergeAbbrev quadratic: every sentence ends
// at an abbreviation, so the whole document merges into one group.
func abbrevDoc(n int) string { return strings.Repeat("Run it on a file, e.g. ", n) }

func BenchmarkDetectLongSentenceAbbrev(b *testing.B) {
	for _, n := range []int{500, 1000, 2000, 4000} {
		doc := abbrevDoc(n)
		b.Run(itoa(n), func(b *testing.B) {
			b.SetBytes(int64(len(doc)))
			for i := 0; i < b.N; i++ {
				DetectLongSentence(doc)
			}
		})
	}
}
